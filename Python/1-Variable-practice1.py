first_name = "lee"
last_name = "jungsu"

# 문자열 덧셈: 두 문자열을 하나로 연결한다.
full_name = first_name + " " + last_name
print(full_name)

# 문자열 곱셈: 문자열을 지정한 횟수만큼 반복한다.
repeat_name = first_name * 3
print(repeat_name)

